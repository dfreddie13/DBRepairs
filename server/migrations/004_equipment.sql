CREATE TABLE IF NOT EXISTS equipment (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id bigint NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
  device_type text,
  brand text,
  model text,
  serial_number text,
  imei text,
  notes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS equipment_customer_id_idx ON equipment(customer_id);
CREATE INDEX IF NOT EXISTS equipment_serial_number_idx ON equipment(serial_number);

ALTER TABLE repairs ADD COLUMN IF NOT EXISTS equipment_id bigint REFERENCES equipment(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS repairs_equipment_id_idx ON repairs(equipment_id);
